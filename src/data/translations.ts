export const translations: Record<Language, Partial<Record<TranslationKey, string>>> = { en, ta };

export type TranslateVars = Record<string, string | number>;

export function translate(language: Language, key: TranslationKey, vars?: TranslateVars): string {
  const template = translations[language]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return Object.keys(vars).reduce(
    (acc, varKey) => acc.split(`{${varKey}}`).join(String(vars[varKey])),
    template,
  );
}

export type Translator = (key: TranslationKey, vars?: TranslateVars) => string;

export function createTranslator(language: Language): Translator {
  return (key, vars) => translate(language, key, vars);
}

